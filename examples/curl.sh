#!/usr/bin/env bash
#
# The Soumit API from a terminal. Requires curl and jq.
#
#   export SOUMIT_API_KEY=sk_live_…
#   ./examples/curl.sh
#
set -euo pipefail

BASE="${SOUMIT_BASE_URL:-https://soumit.ma}"

# --- no key required ---------------------------------------------------------

echo "== Service index (unauthenticated on purpose) =="
curl -sS "$BASE/api/v1" | jq '{version, resources: (.resources | length), scopes}'

echo
echo "== The contract, generated by the deployment serving it =="
curl -sS "$BASE/api/v1/openapi.json" | jq '{title: .info.title, version: .info.version, paths: (.paths | length)}'

if [[ -z "${SOUMIT_API_KEY:-}" ]]; then
  echo
  echo "Set SOUMIT_API_KEY to run the authenticated examples."
  echo "Request one: abdel@envoisms.ma"
  exit 0
fi

AUTH=(-H "Authorization: Bearer $SOUMIT_API_KEY")

# --- tenders -----------------------------------------------------------------

echo
echo "== Five open tenders =="
curl -sS "${AUTH[@]}" "$BASE/api/v1/tenders?limit=5&status=open" \
  | jq -r '.data[] | "\(.deadline // "no deadline")  \(.buyer.name // "?")  \(.title)"'

echo
echo "== Budget, without inventing one =="
# amount is null when the notice published nothing usable; `raw` keeps whatever
# the buyer actually wrote, and `unavailable` says which case you are in.
curl -sS "${AUTH[@]}" "$BASE/api/v1/tenders?limit=5" \
  | jq -r '.data[] | "\(.budget.amount // "—")  \(.budget.currency // "")  \(.unavailable.budget_amount // "published")"'

echo
echo "== Rate-limit headers (on every response) =="
curl -sS -D- -o /dev/null "${AUTH[@]}" "$BASE/api/v1/tenders?limit=1" \
  | grep -i -E "^(ratelimit|x-request-id)" || true

# --- pagination --------------------------------------------------------------

echo
echo "== Two pages via cursor =="
PAGE1=$(curl -sS "${AUTH[@]}" "$BASE/api/v1/tenders?limit=3")
echo "$PAGE1" | jq -r '.data[].id'
CURSOR=$(echo "$PAGE1" | jq -r '.next_cursor // empty')
if [[ -n "$CURSOR" ]]; then
  echo "  --- next page ---"
  curl -sS "${AUTH[@]}" "$BASE/api/v1/tenders?limit=3&cursor=$CURSOR" | jq -r '.data[].id'
fi

# --- awards ------------------------------------------------------------------

echo
echo "== Awards, grouped by canonical key rather than display name =="
curl -sS "${AUTH[@]}" "$BASE/api/v1/awards?limit=100" \
  | jq -r '
      [ .data[]
        | select(.is_unsuccessful | not)
        | select(.awarded_amount != null)
        | {key: (.awardee.canonical_key // .awardee.name), name: .awardee.name,
           amount: .awarded_amount, basis: (.amount_basis // "unstated")} ]
      | group_by(.basis)[]
      | "── basis: \(.[0].basis)",
        ( group_by(.key) | sort_by(-([.[].amount] | add))[:5][]
          | "   \([.[].amount] | add | floor)  \(.[0].name)" )'

# --- usage -------------------------------------------------------------------

echo
echo "== Your metered usage (rate_limited counts 429s) =="
curl -sS "${AUTH[@]}" "$BASE/api/v1/usage" | jq '.'

# --- errors ------------------------------------------------------------------

echo
echo "== An error, with its stable code =="
# Over the maximum page size: an error rather than a silent clamp, so a client
# asking for 5000 rows is never handed 100 that look complete.
curl -sS "${AUTH[@]}" "$BASE/api/v1/tenders?limit=5000" | jq '.error | {code, param, message}'
